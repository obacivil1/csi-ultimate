def card_text(row: dict) -> str:
    """نص البطاقة الكامل للنسخ/الحفظ/الطباعة — دالة صرفة."""
    r = row or {}
    im = get(r.get("code", ""))
    lines = [
        f"الثغرة: {r.get('name', '')}  "
        f"[{'مؤكدة ✓' if r.get('verdict') else 'غير مؤكدة'}]",
        f"الكود: {r.get('code', '')} · {r.get('owasp', '')} · "
        f"الخطورة: {r.get('severity', '')} · النمط: {r.get('mode', '')}",
        f"الدليل: {r.get('note', '')}",
        f"الشاهد: {r.get('evidence', '')}",
        "",
        f"👑 تملك الآن: {im['owns']}",
        f"👁 سترى: {im['see']}",
        f"➡ التالي ضمن التفويض: {im['next']}",
        f"💰 الباونتي: {im['bounty']}",
    ]
    return "\n".join(lines)
