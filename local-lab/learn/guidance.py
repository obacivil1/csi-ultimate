def progress_path():
    p = Path(__file__).resolve().parents[1] / "data" / "guidance.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    return p


def load_progress(path=None) -> set:
    path = Path(path) if path else progress_path()
    if not path.exists():
        return set()
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return set(data.get("done", []))
    except Exception:
        return set()


def save_progress(done: set, path=None) -> None:
    path = Path(path) if path else progress_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"done": sorted(done)}, ensure_ascii=False,
                               indent=1), encoding="utf-8")
